# Женская форма фамилии, изменяющейся по родам
def surname_female(surname: str) -> str:
    if surname.endswith(("ов", "ев", "ин", "ын")):
        return surname + "а"
    if surname.endswith("ний"):
        return surname[:-2] + "яя"
    return surname[:-2] + "ая"


def random_fio(rng, female: bool) -> str:
    """
    Случайное ФИО заданного пола
    Часть ФИО собирается без отчества, чтобы сеть не полагалась только на него
    """
    kind = rng.random()
    if kind < 0.65:
        surname = surnames_male[rng.integers(len(surnames_male))]
        surname = surname_female(surname) if female else surname
    elif kind < 0.97:
        surname = surnames_neutral[rng.integers(len(surnames_neutral))]
    else:
        surname = surnames_special[rng.integers(len(surnames_special))][int(female)]

    names = names_female if female else names_male
    fio = [surname, names[rng.integers(len(names))]]

    kind = rng.random()
    if kind < 0.8:
        stem = patronymic_stems[rng.integers(len(patronymic_stems))]
        fio.append(stem + ("на" if female else "ич"))
    elif kind < 0.86:
        fio.append(patronymic_special[rng.integers(len(patronymic_special))][int(female)])
    elif kind < 0.9:
        father = patronymic_turkic[rng.integers(len(patronymic_turkic))]
        fio.append(father + (" кызы" if female else " оглы"))

    return " ".join(fio)
